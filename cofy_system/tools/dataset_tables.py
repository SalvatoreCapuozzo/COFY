#!/usr/bin/env python3
"""Use-case tables of the paper from the images each run actually trained on.

KFM12 and WBC train on a class-stratified tenth of each node's training images, drawn with the seed
(cofy/sampling.py); every run writes the list it used to <run>/<mode>/balanced_subsets/<node>_train.txt.
DENTEX trains on every training image. This script reads those lists for the confirmation seeds
(100-109, CWT runs: every arm of a seed uses the same subset) and writes analysis/DATASET_TABLES.md:

  - per use case: unique training images per seed, the share of a node's training images that also
    contain classes of other nodes (seen unlabelled), and the imbalance (commonest / rarest class);
  - per class: labelled instances trained on (mean and range over seeds), in the full training split
    the subsets are drawn from, and in the evaluation set;
  - training exposure, the same for the centralized reference and every scheme: examples per epoch
    (an image with one node's partial labels), optimizer steps (batches of four), and the summed
    learning rate of the federated nodes relative to centralized, lowered by the warm-up that restarts
    at every round or turn.

    python tools/dataset_tables.py
"""
import math
import statistics
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
VAR = ROOT / "runs/variants"
SEEDS = range(100, 110)
VARIANT = "confirm_v2sync"
DATASETS = ["kfm12", "wbc", "dentex"]


def node_files(cfg, ds, s, node):
    """The images the node trained on in seed s (file paths), and whether a subset list was found."""
    root = ROOT / Path(node["data_yaml"]).parent
    man = next((VAR / f"{VARIANT}/{ds}/s{s}").glob(f"*/balanced_subsets/{node['name']}_train.txt"), None)
    if man:
        return [Path(line) for line in man.read_text().splitlines() if line.strip()], True
    return sorted((root / "images/train").iterdir()), False


def count_boxes(root, names, files, split="train"):
    boxes = {}
    for f in files:
        lbl = root / "labels" / split / (Path(f).stem + ".txt")
        if lbl.exists():
            for line in lbl.read_text().splitlines():
                if line.strip():
                    c = names[int(line.split()[0])]
                    boxes[c] = boxes.get(c, 0) + 1
    return boxes


def main():
    out = ["# Use-case tables", "", "Generated by `tools/dataset_tables.py` from the training subsets of the "
           f"confirmation seeds ({VARIANT}, seeds 100-109).", ""]
    exposure = []
    for ds in DATASETS:
        per_seed = []
        for s in SEEDS:
            cfg = yaml.safe_load((ROOT / f"configs/variants/{VARIANT}/{ds}_s{s}.yaml").read_text())
            pools = {n["name"]: {p.name for p in (ROOT / Path(n["data_yaml"]).parent / "images/train").iterdir()}
                     for n in cfg["nodes"]}
            boxes, sizes, uniq, unl = {}, {}, set(), []
            for n in cfg["nodes"]:
                root = ROOT / Path(n["data_yaml"]).parent
                names = yaml.safe_load((root / "data.yaml").read_text())["names"]
                files, _ = node_files(cfg, ds, s, n)
                sizes[n["name"]] = len(files)
                uniq |= {Path(f).name for f in files}
                other = set().union(*(v for k, v in pools.items() if k != n["name"]))
                unl.append(sum(Path(f).name in other for f in files) / len(files))
                for c, k in count_boxes(root, names, files).items():
                    boxes[c] = boxes.get(c, 0) + k
            fed = cfg["federation"]
            warm = fed["warmup_steps"]
            lost = sum((warm - 1 - k) / warm for k in range(warm))      # step-equivalents lost per warm-up
            epochs = fed["async_node_cycles"] * fed["local_epochs"]
            steps_epoch = sum(math.ceil(v / fed["batch_size"]) for v in sizes.values())
            turn = [fed["local_epochs"] * math.ceil(v / fed["batch_size"]) for v in sizes.values()]
            fed_mass = sum(fed["async_node_cycles"] * (t - lost) for t in turn)
            cen_mass = epochs * steps_epoch - lost
            per_seed.append({"boxes": boxes, "uniq": len(uniq), "examples": sum(sizes.values()),
                             "steps_epoch": steps_epoch, "epochs": epochs, "steps": epochs * steps_epoch,
                             "unlabelled": statistics.mean(unl), "lr": 100 * (fed_mass / cen_mass - 1),
                             "nodes": cfg["nodes"]})
        # full training split and evaluation set
        cfg = yaml.safe_load((ROOT / f"configs/variants/{VARIANT}/{ds}_s100.yaml").read_text())
        split, owner = {}, {}
        for n in cfg["nodes"]:
            root = ROOT / Path(n["data_yaml"]).parent
            names = yaml.safe_load((root / "data.yaml").read_text())["names"]
            for c, k in count_boxes(root, names, sorted((root / "images/train").iterdir())).items():
                split[c] = split.get(c, 0) + k
            for c in n["owned_classes"]:
                owner[c] = n["name"][-1]
        ev_root = ROOT / Path(cfg["eval_data_yaml"]).parent
        ev_names = yaml.safe_load((ROOT / cfg["eval_data_yaml"]).read_text())["names"]
        ev_names = [ev_names[i] for i in range(len(ev_names))] if isinstance(ev_names, dict) else ev_names
        ev_files = [p for p in (ev_root / "labels").rglob("*.txt")]
        ev = {}
        for f in ev_files:
            for line in f.read_text().splitlines():
                if line.strip():
                    c = ev_names[int(line.split()[0])]
                    ev[c] = ev.get(c, 0) + 1
        m = lambda k: statistics.mean(p[k] for p in per_seed)
        cls = sorted(split, key=lambda c: -statistics.mean(p["boxes"].get(c, 0) for p in per_seed))
        mean_box = {c: statistics.mean(p["boxes"].get(c, 0) for p in per_seed) for c in cls}
        out += [f"## {ds}", "",
                f"Unique training images per seed: mean {m('uniq'):.0f} (range {min(p['uniq'] for p in per_seed)}-"
                f"{max(p['uniq'] for p in per_seed)}); node images seen with other nodes' classes unlabelled: "
                f"{100 * m('unlabelled'):.0f} %; imbalance (commonest / rarest class, mean counts): "
                f"{max(mean_box.values()) / min(mean_box.values()):.1f}x.", "",
                "| class | owner | trained on (mean) | range over seeds | full training split | evaluation set |",
                "|---|---|---|---|---|---|"]
        for c in cls:
            v = [p["boxes"].get(c, 0) for p in per_seed]
            out.append(f"| {c} | {owner[c]} | {mean_box[c]:.1f} | {min(v)}-{max(v)} | {split[c]} | {ev.get(c, 0)} |")
        out.append("")
        exposure.append((ds, m("uniq"), m("examples"), m("steps_epoch"), per_seed[0]["epochs"], m("steps"), m("lr")))
    out += ["## Training exposure (the same for the centralized reference and every scheme, except the last column)", "",
            "| use case | unique images | examples per epoch | steps per epoch | epochs | steps | summed learning rate, federated vs centralized |",
            "|---|---|---|---|---|---|---|"]
    out += [f"| {ds} | {u:.0f} | {e:.0f} | {se:.0f} | {ep} | {st:.0f} | {lr:+.1f} % |" for ds, u, e, se, ep, st, lr in exposure]
    text = "\n".join(out) + "\n"
    (ROOT / "analysis/DATASET_TABLES.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
