#!/usr/bin/env python3
"""Room configs for the multi-machine experiments (MULTI_MACHINE_EXPERIMENTS.md at the repository root).

Each config is the frozen configuration of a simulated run of the study, so that the networked run can be
compared with it seed by seed, with only what a network room needs changed:
  - federation.mode: the simulator takes the mode from its command line, a room from the config
    (CWT and FedAsync are 'async' rooms; FedAvg is 'sync');
  - federation.final_calibration: true, so that the nodes run the calibration over the network
    (the study calibrated the simulated runs afterwards, tools/calibrate_checkpoints.py);
  - output_dir: runs/net/<experiment>, never a folder of the study;
  - --scale s|m (optional): a smaller YOLO26 scale, when two nodes must share a GPU that cannot hold two
    copies of scale l; such a run is then compared with a simulated run of the same config (the tool
    prints the command), not with the study.
The simulator's virtual-clock settings are ignored by rooms: on separate machines, timing is real.

Writes configs/net/<use case>_<scheme>_s<seed>.yaml and configs/net/index.json (for each experiment: its
simulated counterpart, the calibration stage it was registered with, the centralized reference).

    python tools/make_net_configs.py                      # seeds 100-102, scale l
    python tools/make_net_configs.py --scale s --seeds 100
    python tools/make_net_configs.py --smoke              # a few-minute WBC room to test the machines
"""
import argparse, json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
V = ROOT / "configs/variants"
SCHEMES = {   # name: (source variant, room mode, registered calibration stage of the source)
    "cwt": ("confirm_v2sync", "async", "bn+head"),
    "fedasync": ("confirm_v2async", "async", "acal_refresh"),
}


def write(cfg, name, src, stage, ds, seed, index, scale):
    f = cfg["federation"]
    if scale != "l":
        cfg["model"]["arch"] = cfg["model"]["arch"].replace("_l.yaml", f"_{scale}.yaml")
        name += f"_{scale}"
    cfg["output_dir"] = f"runs/net/{name}"
    out = ROOT / "configs/net" / f"{name}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    head = (f"# Multi-machine experiment {name} (MULTI_MACHINE_EXPERIMENTS.md): the configuration of the simulated\n"
            f"# run {src}/{ds}_s{seed}.yaml, with mode {f['mode']}, calibration over the network and its own output\n"
            f"# folder. Generated by tools/make_net_configs.py.\n")
    out.write_text(head + yaml.safe_dump(cfg, sort_keys=False))
    index[name] = {"config": str(out.relative_to(ROOT)), "use_case": ds, "seed": seed, "scale": scale,
                   "simulated": None if scale != "l" else {"variant": src, "stage": stage,
                                                           "result": f"runs/variants/calib/{src}/{ds}/s{seed}/async.json"
                                                           if src.startswith("confirm") else
                                                           f"runs/variants/calib/{src}/{ds}/s{seed}/sync.json"},
                   "centralized": {"result": f"runs/variants/calib/v2_centralized/{ds}/s{seed}/centralized.json",
                                   "stage": "bn+head"}}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, nargs="+", default=[100, 101, 102])
    ap.add_argument("--use-cases", nargs="+", default=["wbc", "dentex", "kfm12"])
    ap.add_argument("--scale", choices=["l", "m", "s"], default="l")
    ap.add_argument("--smoke", action="store_true", help="only a short CWT room on WBC (1 cycle, 2%% of the images)")
    a = ap.parse_args()
    if a.smoke:
        idx_path = ROOT / "configs/net/index.json"
        index = json.loads(idx_path.read_text()) if idx_path.exists() else {}
        cfg = yaml.safe_load((V / "confirm_v2sync/wbc_s100.yaml").read_text())
        f = cfg["federation"]
        f.update({"mode": "async", "final_calibration": True, "async_node_cycles": 1, "rounds": 1,
                  "local_epochs": 1, "balanced_fraction": 0.02})
        print(write(cfg, "smoke_wbc_cwt", "confirm_v2sync", "bn+head", "wbc", 100, index, a.scale).relative_to(ROOT))
        index["smoke_wbc_cwt"]["simulated"] = None   # a test, not comparable with the study
        idx_path.write_text(json.dumps(index, indent=1))
        return
    idx_path = ROOT / "configs/net/index.json"
    index = json.loads(idx_path.read_text()) if idx_path.exists() else {}
    for ds in a.use_cases:
        for seed in a.seeds:
            for scheme, (src, mode, stage) in SCHEMES.items():
                cfg = yaml.safe_load((V / src / f"{ds}_s{seed}.yaml").read_text())
                cfg["federation"]["mode"] = mode
                cfg["federation"]["final_calibration"] = True
                print(write(cfg, f"{ds}_{scheme}_s{seed}", src, stage, ds, seed, index, a.scale).relative_to(ROOT))
    # FedAvg: development configuration (it was not confirmed), seed 0 of WBC, for the wall-clock comparison
    if "wbc" in a.use_cases:
        cfg = yaml.safe_load((V / "v2_sync/wbc_s0.yaml").read_text())
        cfg["federation"]["mode"] = "sync"
        cfg["federation"]["final_calibration"] = True
        print(write(cfg, "wbc_fedavg_s0", "v2_sync", "bn+head", "wbc", 0, index, a.scale).relative_to(ROOT))
    idx_path.write_text(json.dumps(index, indent=1))
    if a.scale != "l":
        print("\nscale", a.scale, "has no simulated counterpart in the study; simulate it on one machine with, e.g.:\n"
              f"  python -m cofy.simulate --config configs/net/wbc_cwt_s{a.seeds[0]}_{a.scale}.yaml --session s{a.seeds[0]} --mode async")


if __name__ == "__main__":
    main()
