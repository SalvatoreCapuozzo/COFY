#!/usr/bin/env python3
"""Cost of each scheme: GPU time, energy, communication and deployment wall-clock.

- GPU time: minutes per run from the runner logs (simulation: every node trained in turn on
  this machine's single GPU, so it is the total compute, not the deployment time).
- Energy: integrated from runs/variants/_power.csv (nvidia-smi power draw every 10 s) over each
  run's interval, when the log covers it; otherwise estimated as minutes x the median
  training power measured there (marked "est.").
- Communication: model transfers x the size of the model state (fp32), per node and in total;
  the calibration exchange (BatchNorm statistics + owned class rows) separately.
- Deployment wall-clock, from the concurrent runs' virtual schedules (per-node turn durations
  drawn from data size x machine speed): sequential = sum of every node's turns; parallel
  FedAvg = per round the slowest node; concurrent = the last update's arrival.

    python tools/cost_report.py [--out analysis/COST.md]
"""
import json, re, statistics, sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VAR = ROOT / "runs/variants"
DATASETS = ["kfm12", "wbc", "chestx", "dentex"]
SCHEMES = [("centralized", "v2_central", "calib_v2_central"), ("sync sequential", "v2_async", "calib_v2_async"),
           ("async concurrent", "v2_vclock", "calib_v2_vclock"), ("sync parallel FedAvg", "v2_sync", "calib_v2_sync"),
           ("centralized (confirmation)", "confirm_central", "calib_confirm_central"),
           ("sync sequential (confirmation)", "confirm_v2sync", "calib_confirm_v2sync"),
           ("async concurrent (confirmation)", "confirm_v2async", "calib_confirm_v2async")]
MODEL_MB = 99.39      # fp32 state of yolo26-classic-l (measured on a final checkpoint)
CALIB_MB = 0.25 + 0.03   # BatchNorm running statistics + all class rows (cv3.*.2)


def power():
    rows = []
    f = VAR / "_power.csv"
    for line in (f.read_text().splitlines() if f.exists() else []):
        p = [x.strip() for x in line.split(",")]
        try:
            rows.append((datetime.strptime(p[0][:19], "%Y/%m/%d %H:%M:%S"), float(p[1]), float(p[2])))
        except (ValueError, IndexError):
            pass
    return rows


def runs(variant):
    """[(dataset, end datetime, minutes)] from the runner log ('MM-DD HH:MM DONE ... <ds> s<seed> ... in N min')."""
    log = VAR / f"{variant}/_runner.log"
    out = []
    for m in re.finditer(r"^(\d\d-\d\d \d\d:\d\d) DONE\s+(?:\S+ )?(kfm12|wbc|chestx|dentex) s\d+ (?:\w+ )?in (\d+) min",
                         log.read_text() if log.exists() else "", re.M):
        end = datetime.strptime(f"2026-{m.group(1)}", "%Y-%m-%d %H:%M")
        out.append((m.group(2), end, int(m.group(3))))
    return out


def energy_kwh(end, minutes, pw, typical_w):
    start = end.timestamp() - minutes * 60
    w = [p for t, p, _ in pw if start <= t.timestamp() <= end.timestamp() + 60]
    if len(w) >= 0.8 * minutes * 6:        # the log covers the run (one sample every 10 s)
        return statistics.mean(w) * minutes / 60 / 1000, True
    return typical_w * minutes / 60 / 1000, False


def schedules():
    out = {}
    for ds in DATASETS:
        r = []
        for f in sorted(f for v in ("v2_vclock", "confirm_v2async")       # the concurrent scheme's own schedules
                        for f in VAR.glob(f"{v}/{ds}/s*/async/virtual_schedule.json")):
            v = json.loads(f.read_text())
            dur = {n: [e["finish"] - e["start"] for e in v["events"] if e["node"] == n] for n in v["speed"]}
            k = min(len(x) for x in dur.values())
            conc = max(e["finish"] for e in v["events"])
            r.append((sum(map(sum, dur.values())) / conc,
                      sum(max(d[i] for d in dur.values()) for i in range(k)) / conc, k))
        if r:
            out[ds] = tuple(statistics.mean(x[i] for x in r) for i in range(2)) + (r[0][2], len(r))
    return out


def main():
    pw = power()
    train_w = [p for _, p, u in pw if u >= 50]
    typical_w = statistics.median(train_w) if train_w else 80.0
    lines = ["# Cost of each scheme", "",
             f"Generated by `tools/cost_report.py`. Hardware: one RTX 3080 Laptop GPU (8 GB). Median power while "
             f"training: {typical_w:.0f} W ({len(pw)} samples in `runs/variants/_power.csv`).", "",
             "## GPU time and energy per run (simulation on one GPU, training + calibration)", "",
             "| scheme | dataset | runs | train min (median) | calibration min | energy kWh per run |", "|---|---|---|---|---|---|"]
    for label, var, cal in SCHEMES:
        for ds in DATASETS:
            tr = [r for r in runs(var) if r[0] == ds]
            cb = [r for r in runs(cal) if r[0] == ds]
            if not tr:
                continue
            e = [energy_kwh(end, m, pw, typical_w) for _, end, m in tr + cb]
            measured = all(x[1] for x in e)
            lines.append(f"| {label} | {ds} | {len(tr)} | {statistics.median(m for *_, m in tr):.0f} | "
                         f"{statistics.median(m for *_, m in cb) if cb else 0:.0f} | "
                         f"{sum(x[0] for x in e) / len(tr):.2f}{'' if measured else ' est.'} |")
    sch = schedules()
    lines += ["", "## Communication (fp32 model, every scheme: one download + one upload per node turn)", "",
              "| dataset | turns per node | per node GB | total GB (4 nodes) | calibration exchange per node |",
              "|---|---|---|---|---|"]
    for ds, (_, _, k, _) in sch.items():
        lines.append(f"| {ds} | {k} | {2 * k * MODEL_MB / 1000:.1f} | {8 * k * MODEL_MB / 1000:.1f} | "
                     f"{2 * MODEL_MB + CALIB_MB:.1f} MB (model + {CALIB_MB:.2f} MB of statistics and class rows) |")
    lines += ["", "## Deployment wall-clock (4 machines of different speed, relative to the concurrent scheme)", "",
              "| dataset | schedules | concurrent async | parallel FedAvg | sequential sync |", "|---|---|---|---|---|"]
    for ds, (seq, par, _, n) in sch.items():
        lines.append(f"| {ds} | {n} | 1.00 | {par:.2f} | {seq:.2f} |")
    if sch:
        lo, hi = min(x[0] for x in sch.values()), max(x[0] for x in sch.values())
        lines += ["", "Sequential turns cost wall-clock time, not compute: every scheme trains the same number of "
                  f"node-epochs. A 4-node federation waits about {lo:.1f}-{hi:.1f} times longer for the sequential model."]
    text = "\n".join(lines)
    print(text)
    if "--out" in sys.argv:
        Path(sys.argv[sys.argv.index("--out") + 1]).write_text(text + "\n")


if __name__ == "__main__":
    main()
